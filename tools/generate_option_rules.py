#!/usr/bin/env python3
"""Generate the process settings rules from the desktop app's ConfigManipulation.cpp.

OrcaSlicer's ConfigManipulation::toggle_print_fff_options() decides, from a
config, which process settings are greyed out (toggle_field) or hidden
(toggle_line), and why. It is GUI code only in name: the decisions read the
config through libslic3r. This script copies the function's body into a C++
fragment the bridge compiles (native/bridge/src/OptionRules.cpp), replacing
the GUI's few dependencies with the rule context's:

- ``_L("text")`` / ``L("text")`` / ``wxString``  -> ``std::string``
- the edited printer preset's config              -> ``printer_config``
- ``wxGetApp()``'s printer type for wrapping detection -> not supported (hidden)

``toggle_field``, ``toggle_line``, ``set_option_label`` and ``apply`` keep their
names: the context records them (OptionRules.cpp).

Rerun it after bumping the OrcaSlicer submodule:

    tools/generate_option_rules.py third_party/OrcaSlicer native/bridge/src/generated/ProcessOptionRules.inc
"""
import re
import subprocess
import sys

FUNCTION = 'void ConfigManipulation::toggle_print_fff_options('


def function_body(source: str, signature: str) -> str:
    start = source.index(signature)
    brace = source.index('{', start)
    depth = 0
    for i in range(brace, len(source)):
        if source[i] == '{':
            depth += 1
        elif source[i] == '}':
            depth -= 1
            if depth == 0:
                return source[brace + 1:i]
    raise ValueError(f'unbalanced braces in {signature}')


def transform(body: str) -> str:
    out = []
    for line in body.split('\n'):
        stripped = line.strip()
        # The bundle is reached only through the edited printer preset, which the context passes in.
        if stripped.startswith('PresetBundle *preset_bundle'):
            continue
        # Printer types come from the desktop's device database, which the app does not ship:
        # wrapping detection is treated as unsupported, as for any printer outside it.
        if 'get_printer_type(' in line:
            continue
        line = line.replace('DevPrinterConfigUtil::support_wrapping_detection(printer_type)', 'false')
        line = line.replace('preset_bundle->printers.get_edited_preset().config', 'printer_config')
        line = re.sub(r'\b_L\(', 'std::string(', line)
        line = re.sub(r'(?<![\w_])L\(', 'std::string(', line)
        line = re.sub(r'\bwxString\b', 'std::string', line)
        out.append(line)
    text = '\n'.join(out)
    leftover = [w for w in ('wxGetApp', 'preset_bundle', 'GUI::', 'wxID_', 'MessageDialog') if w in text]
    if leftover:
        raise ValueError(f'the rules use something the generator does not translate: {leftover}')
    return text


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    orca, output = sys.argv[1], sys.argv[2]
    path = f'{orca}/src/slic3r/GUI/ConfigManipulation.cpp'
    with open(path, encoding='utf-8') as f:
        source = f.read()
    try:
        commit = subprocess.run(['git', '-C', orca, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True,
                                check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = 'unknown'
    body = transform(function_body(source, FUNCTION))
    with open(output, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/generate_option_rules.py from OrcaSlicer '
                f'{commit}: src/slic3r/GUI/ConfigManipulation.cpp,\n'
                '// ConfigManipulation::toggle_print_fff_options(). Do not edit; rerun the script.\n'
                '// Included in the body of ProcessRules::run() (OptionRules.cpp).\n')
        f.write(body.strip('\n') + '\n')


if __name__ == '__main__':
    main()
